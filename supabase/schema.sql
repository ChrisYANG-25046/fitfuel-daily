-- ===================================================
-- Supabase Schema for Meal Tracker (FitFuel Daily)
-- ===================================================

-- 1. 创建 meals 数据表 (包含 PFC 字段)
create table if not exists public.meals (
  id bigint generated by default as identity primary key,
  food_name text not null,
  calories integer not null check (calories >= 0),
  protein numeric default 0 check (protein >= 0),
  fat numeric default 0 check (fat >= 0),
  carbs numeric default 0 check (carbs >= 0),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 若已存在早期版本的 meals 表，可运行以下脚本补充 PFC 字段：
alter table public.meals 
  add column if not exists protein numeric default 0,
  add column if not exists fat numeric default 0,
  add column if not exists carbs numeric default 0;

-- 开启 meals 表行级安全策略 (RLS)
alter table public.meals enable row level security;

create policy "Allow anonymous select on meals"
  on public.meals for select to anon, authenticated using (true);
create policy "Allow anonymous insert on meals"
  on public.meals for insert to anon, authenticated with check (true);
create policy "Allow anonymous delete on meals"
  on public.meals for delete to anon, authenticated using (true);

create index if not exists idx_meals_created_at on public.meals (created_at desc);

-- ===================================================
-- 2. 创建 presets (マイセット / 常用食谱) 数据表 (Week 3)
-- ===================================================
create table if not exists public.presets (
  id bigint generated by default as identity primary key,
  food_name text not null,
  calories integer not null check (calories >= 0),
  protein numeric default 0 check (protein >= 0),
  fat numeric default 0 check (fat >= 0),
  carbs numeric default 0 check (carbs >= 0),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 开启 presets 表行级安全策略 (RLS)
alter table public.presets enable row level security;

create policy "Allow anonymous select on presets"
  on public.presets for select to anon, authenticated using (true);
create policy "Allow anonymous insert on presets"
  on public.presets for insert to anon, authenticated with check (true);
create policy "Allow anonymous delete on presets"
  on public.presets for delete to anon, authenticated using (true);

create index if not exists idx_presets_created_at on public.presets (created_at asc);

-- ===================================================
-- 3. 创建 user_settings (用户目标与设置) 数据表
-- ===================================================
create table if not exists public.user_settings (
  id bigint generated by default as identity primary key,
  target_calories integer not null default 2000 check (target_calories > 0),
  target_protein numeric default 150 check (target_protein >= 0),
  target_fat numeric default 50 check (target_fat >= 0),
  target_carbs numeric default 200 check (target_carbs >= 0),
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 开启 user_settings 表行级安全策略 (RLS)
alter table public.user_settings enable row level security;

create policy "Allow anonymous select on user_settings"
  on public.user_settings for select to anon, authenticated using (true);
create policy "Allow anonymous insert on user_settings"
  on public.user_settings for insert to anon, authenticated with check (true);
create policy "Allow anonymous update on user_settings"
  on public.user_settings for update to anon, authenticated using (true);

-- 初始化默认配置数据（如果尚未存在）
insert into public.user_settings (id, target_calories, target_protein, target_fat, target_carbs)
values (1, 2000, 150, 50, 200)
on conflict (id) do nothing;
